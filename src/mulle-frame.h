#define MULLE__FRAME_VERSION  ((0 << 20) | (7 << 8) | 56)


static inline unsigned int   mulle_frame_get_version_major( void)
{
   return( MULLE__FRAME_VERSION >> 20);
}


static inline unsigned int   mulle_frame_get_version_minor( void)
{
   return( (MULLE__FRAME_VERSION >> 8) & 0xFFF);
}


static inline unsigned int   mulle_frame_get_version_patch( void)
{
   return( MULLE__FRAME_VERSION & 0xFF);
}


